# $( )로 감싸면 안쪽이 먼저 실행되고 그 결과가 자리에 들어갑니다
#   date +%Y는 오늘 날짜에서 연도 네 자리만 뽑습니다 (날짜 형식은 3장에서 자세히)
echo "올해는 $(date +%Y)년"
#   올해는 2026년

# 감싸지 않으면 글자 그대로입니다 — 차이를 눈으로 보세요
echo "올해는 date +%Y년"
#   올해는 date +%Y년

# 줄 수를 세어 변수에 담을 때도 같은 문법입니다
echo "access.log는 $(wc -l < access.log) 줄"
#   access.log는 8 줄
#   (macOS는 숫자 앞에 공백이 붙어 「access.log는        8 줄」로 나옵니다 — 3장에서 tr로 뗍니다)

# seq는 숫자를 한 줄에 하나씩 냅니다
seq 1 5
#   1
#   2
#   3
#   4
#   5
